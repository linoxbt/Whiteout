#!/usr/bin/env python3
"""Generate move/whiteout/tests/fixtures.move.

Move tests cannot sign, so this script plays the dealer for one fixed test game:
it derives the game's object ID the way Sui does, lays out a test map, and signs
every tile's kind (and two deals) with a fixed Ed25519 key.

Game ID: the tests create the lobby first in a TxContext built with
`tx_context::new(sender, TX_HASH, 0, 0, 0)`, so the Game's UID is
ObjectID::derive_id(TX_HASH, 0) = blake2b256(0xf1 || TX_HASH || 0u64 LE).
`fixtures_tests::game_id_matches` fails loudly if that ever stops holding.

Run from the repo root:  python3 move/whiteout/scripts/gen_fixtures.py
Needs the `cryptography` package.
"""

import hashlib
import random
from pathlib import Path

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

GRID = 24
SNOW, CREVASSE, GOGGLES, ROPE, RELIC = range(5)
INTENT_DEAL, INTENT_TILE_KIND = 1, 2

TX_HASH = bytes([0x11] * 32)
DEAL_TS = 1_765_000_000_000
DEALER_SEED = bytes([0x2A] * 32)

OUT = Path(__file__).resolve().parent.parent / "tests" / "fixtures.move"


def derive_id(tx_hash: bytes, n: int) -> bytes:
    return hashlib.blake2b(b"\xf1" + tx_hash + n.to_bytes(8, "little"), digest_size=32).digest()


def uleb(n: int) -> bytes:
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def intent(scope: int, ts: int, payload: bytes) -> bytes:
    """BCS of enclave::IntentMessage { intent: u8, timestamp_ms: u64, payload }."""
    return bytes([scope]) + ts.to_bytes(8, "little") + payload


def kind_msg(game_id: bytes, x: int, y: int, kind: int) -> bytes:
    """BCS of IntentMessage<tiles::TileKind { game_id: ID, x, y, kind }>."""
    return intent(INTENT_TILE_KIND, DEAL_TS, game_id + bytes([x, y, kind]))


def deal_msg(game_id: bytes, ct_hash: bytes) -> bytes:
    """BCS of IntentMessage<tiles::DealPayload { game_id, grid: 24, tiles: 576, ct_hash }>."""
    payload = game_id + bytes([GRID]) + (576).to_bytes(2, "little") + uleb(len(ct_hash)) + ct_hash
    return intent(INTENT_DEAL, DEAL_TS, payload)


# Hand-placed tiles the unit tests walk through. Everything else is random.
LANES = {
    # Column 5: snow, goggles, rope, crevasse, then snow up to the relic at row 12.
    (5, 1): SNOW, (5, 2): GOGGLES, (5, 3): ROPE, (5, 4): CREVASSE,
    **{(5, y): SNOW for y in range(5, 12)},
    (5, 12): RELIC,
    # Column 4: four ropes in a row (rope cap test).
    (4, 1): ROPE, (4, 2): ROPE, (4, 3): ROPE, (4, 4): ROPE,
    # A crevasse right next to base camp (fatal test) and beside the lane.
    (6, 1): CREVASSE, (7, 1): CREVASSE,
    # Column 9: snow for walking tests.
    **{(9, y): SNOW for y in range(1, 24)},
    # Column 0: goggles then snow (vision countdown test).
    (0, 1): GOGGLES, **{(0, y): SNOW for y in range(2, 24)},
    # Column 1: second pair of goggles at row 5 (reset test).
    **{(1, y): SNOW for y in range(1, 24) if y != 5}, (1, 5): GOGGLES,
}


def build_map() -> list[int]:
    rng = random.Random(7)
    kinds = [SNOW] * (GRID * GRID)
    for (x, y), k in LANES.items():
        kinds[y * GRID + x] = k
    free = [
        (x, y)
        for y in range(1, GRID)
        for x in range(GRID)
        if (x, y) not in LANES
    ]
    rng.shuffle(free)
    placed = {CREVASSE: sum(k == CREVASSE for k in LANES.values()),
              GOGGLES: sum(k == GOGGLES for k in LANES.values()),
              ROPE: sum(k == ROPE for k in LANES.values())}
    want = {CREVASSE: 70, GOGGLES: 12, ROPE: 13}
    for kind in (CREVASSE, GOGGLES, ROPE):
        for _ in range(max(0, want[kind] - placed[kind])):
            x, y = free.pop()
            kinds[y * GRID + x] = kind
    return kinds


def hexs(b: bytes) -> str:
    return b.hex()


def main() -> None:
    sk = Ed25519PrivateKey.from_private_bytes(DEALER_SEED)
    pk = sk.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    game_id = derive_id(TX_HASH, 0)
    other_game_id = derive_id(bytes([0x22] * 32), 0)
    ct_hash = hashlib.blake2b(b"whiteout fixture ciphertexts", digest_size=32).digest()

    kinds = build_map()
    sigs = b"".join(
        sk.sign(kind_msg(game_id, i % GRID, i // GRID, k)) for i, k in enumerate(kinds)
    )
    deal_sig = sk.sign(deal_msg(game_id, ct_hash))
    deal_sig_other = sk.sign(deal_msg(other_game_id, ct_hash))
    other_game_sig_5_1 = sk.sign(kind_msg(other_game_id, 5, 1, kinds[1 * GRID + 5]))

    OUT.write_text(f"""// Generated by move/whiteout/scripts/gen_fixtures.py. Do not edit.
#[test_only]
module whiteout::fixtures;

const TX_HASH: vector<u8> = x"{hexs(TX_HASH)}";
const GAME_ID: address = @0x{hexs(game_id)};
const OTHER_GAME_ID: address = @0x{hexs(other_game_id)};
const DEAL_TS: u64 = {DEAL_TS};
const DEALER_PK: vector<u8> = x"{hexs(pk)}";
const CT_HASH: vector<u8> = x"{hexs(ct_hash)}";
const DEAL_SIG: vector<u8> = x"{hexs(deal_sig)}";
const DEAL_SIG_OTHER_GAME: vector<u8> = x"{hexs(deal_sig_other)}";
const OTHER_GAME_SIG_5_1: vector<u8> = x"{hexs(other_game_sig_5_1)}";
/// Kind of tile (x, y) at index y*24+x.
const KINDS: vector<u8> = x"{hexs(bytes(kinds))}";
/// 64-byte kind signature of tile (x, y) at offset (y*24+x)*64.
const SIGS: vector<u8> = x"{hexs(sigs)}";

public fun tx_hash(): vector<u8> {{ TX_HASH }}

public fun game_id(): ID {{ object::id_from_address(GAME_ID) }}

public fun other_game_id(): ID {{ object::id_from_address(OTHER_GAME_ID) }}

public fun deal_ts(): u64 {{ DEAL_TS }}

public fun dealer_pk(): vector<u8> {{ DEALER_PK }}

public fun ct_hash(): vector<u8> {{ CT_HASH }}

public fun deal_sig(): vector<u8> {{ DEAL_SIG }}

public fun deal_sig_other_game(): vector<u8> {{ DEAL_SIG_OTHER_GAME }}

public fun other_game_sig_5_1(): vector<u8> {{ OTHER_GAME_SIG_5_1 }}

public fun kind(x: u8, y: u8): u8 {{
    let kinds = KINDS;
    kinds[(y as u64) * 24 + (x as u64)]
}}

public fun sig(x: u8, y: u8): vector<u8> {{
    let start = ((y as u64) * 24 + (x as u64)) * 64;
    let sigs = SIGS;
    let mut out = vector[];
    64u64.do!(|i| out.push_back(sigs[start + i]));
    out
}}
""")
    print(f"wrote {OUT} (game {game_id.hex()}, relic at (5, 12))")


if __name__ == "__main__":
    main()
